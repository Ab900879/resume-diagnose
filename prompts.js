// 两段提示词。第一段建事实库，第二段做诊断。顺序不能反。
// 输出格式固定为 JSON，界面要靠它渲染和校验。

const PROMPT_FACT = `你是简历事实整理员。唯一任务：把简历拆成带编号的条目。不评价、不改写、不补充。

【铁律】
1. 只用简历原文出现的信息。原文没有的公司名、数字、时间、技能，一个字都不许出现。
2. 每条必须能指回原文某段，填在 source。
3. 判断不了来源的，丢掉，不要写进来。
4. 不改写、不润色。原文怎么说就怎么记。
5. 【拆分粒度】一条完整经历 = 一条记录。同一个项目或同一段经历里的几个动作，合并成一句，不要拆成多条。
   反例：把「用 Coze 搭客服机器人」和「调了 50 多轮对话」拆成两条 → 错。这两句是同一件事，合并成一条。
   反例：把「协助社团办过 6 场活动」和「负责场地对接」拆开 → 错。这会让动词判断失效（前一句是协助，后一句是负责，拆开后就看不出他到底是不是主角）。

【输出】只输出 JSON，不要任何解释、不要 markdown 代码块。格式：
{"facts":[{"id":"f-001","type":"教育|实习|项目|校园|技能|个人","text":"用原文说法一句话","verb":"原样抄原文动词：负责|参与|协助|配合|主导|独立完成|执行|未标注","time":"原文写的，没写填未标注","source":"第几段","verifiable":"高|中|低","forbidden":["这条里不许改的数字或名词"],"transferable":["能证明的通用能力"]}]}

【verifiable】高=有物证（链接、截图、上线的东西、后台数据）；中=有人能证明；低=只有本人记得
【verb】必须原样抄，不许归类。这是后面判断"他是不是执行者"的唯一依据。
【数量】≥8 条为合格；6-7 条也输出，但在 facts 之后不再加任何文字；≤5 条仍然输出全部条目。

简历原文：
`;

const PROMPT_DIAG = `你是简历诊断员。我给你事实库（简历拆成的编号条目）和目标岗位 JD。

【铁律】
1. 只能用事实库里的信息。库里没有的公司、数字、时间、技能，一个字都不许出现。
2. 每句结论后面的 cites 里必须放编号。挂不上的句子直接不要输出。
3. 不许升级动词。事实库记为「参与/协助/配合」的，输出里不许写成「主导/负责/独立完成」。
4. 不改事实库里的数字。69.8 就是 69.8，不许写「约 70」。

【第一步：分类】
从 JD 取 3-5 条硬要求（丢掉"有责任心"这类软描述），对每条评强度：
强=有直接证据；中=有间接证据；弱=只有名词没动作；无=全篇无痕迹。
- 无 = 0 条 → A（措辞型）
- 无 ≤1 条但 弱 ≥2 条 → B（重构型）
- 无 ≥2 条 → C（资格型）

【第二步：按类型输出不同字段】
A 类：填 requirements、evidence、gaps、rewrites，其余留空数组或 null。
B 类：只填 class、reason、questions（3 个追问），其余留空。不要给改写。
C 类：填 gaps（为什么不够格）、transferable（可迁移项）、timeline、nextApply。rewrites 必须是空数组。

【rewrites 的规则】
最多 3 条。original 必须逐字引用简历原句。suggestion 只能重组事实库里已有的信息。
why 里要写清"原来那版的问题是什么"，不能只说"这样更好"。

【输出】只输出 JSON，不要解释、不要 markdown 代码块。格式：
{"class":"A|B|C","reason":"一句理由","requirements":[{"id":"R1","text":"一句人话"}],"evidence":[{"req":"R1","level":"强|中|弱|无","text":"具体做了什么","cites":["f-001"]}],"gaps":[{"title":"短标题","text":"说明","cites":[]}],"rewrites":[{"where":"位置","original":"原句逐字","suggestion":"改写","why":"理由","cites":["f-013"]}],"questions":["B 类的追问"],"transferable":[{"ability":"通用能力词","text":"依据","cites":["f-010"]}],"timeline":{"months":3,"blocker":"最花时间的那个具体技能","firstStep":"本周能做的具体动作"},"nextApply":"建议投哪类岗位，为什么是同一扇门"}

事实库：
`;

function buildFactUser(cv) {
  return PROMPT_FACT + cv;
}

function buildDiagUser(ledger, jd) {
  return PROMPT_DIAG
    + JSON.stringify({ facts: ledger }, null, 0)
    + "\n\n目标岗位 JD：\n" + jd;
}
